using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Newtonsoft.Json.Linq;
using UnityEditor;
using UnityEngine;

namespace Demo3D.EditorTools.Effects
{
    /// <summary>
    /// TD8's inventory (effects.md, The converter): every module enabled, and every shape,
    /// render mode, curve mode, vertex stream and shader in use across the effect candidates
    /// and all their child systems, with the prefabs that use each. The converter is built to
    /// exactly this table.
    /// </summary>
    public static class EffectInventory
    {
        sealed class Uses
        {
            public readonly SortedDictionary<string, SortedSet<string>> Entries = new SortedDictionary<string, SortedSet<string>>();

            public void Add(string key, string prefab)
            {
                if (!Entries.TryGetValue(key, out var set)) Entries[key] = set = new SortedSet<string>();
                set.Add(prefab);
            }
        }

        public static void Run(string outPath)
        {
            var manifest = JObject.Parse(File.ReadAllText("manifest.json"));
            var candidates = manifest["assets"]
                .Where(a => ((string)a["use"]).StartsWith("effect candidate") && ((string)a["path"]).EndsWith(".prefab"))
                .Select(a => (guid: (string)a["guid"], path: (string)a["path"], use: (string)a["use"]))
                .ToList();
            var uses = new Uses();
            var perPrefab = new List<string>();
            foreach (var c in candidates)
            {
                var path = AssetDatabase.GUIDToAssetPath(c.guid);
                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                if (prefab == null) throw new Exception("EffectInventory: missing " + c.path);
                var name = Path.GetFileNameWithoutExtension(path);
                var systems = prefab.GetComponentsInChildren<ParticleSystem>(true);
                int maxParticles = 0;
                var lights = prefab.GetComponentsInChildren<Light>(true).Length;
                foreach (var ps in systems)
                {
                    Inspect(ps, name, uses);
                    maxParticles += ps.main.maxParticles;
                }
                if (lights > 0) uses.Add("component: Light (" + lights + ")", name);
                foreach (var other in prefab.GetComponentsInChildren<Component>(true))
                {
                    if (other == null) { uses.Add("component: missing script", name); continue; }
                    var t = other.GetType();
                    if (t == typeof(Transform) || t == typeof(ParticleSystem) || t == typeof(ParticleSystemRenderer) || t == typeof(Light)) continue;
                    uses.Add("component: " + t.Name, name);
                }
                perPrefab.Add($"| {name} | {c.use.Replace("effect candidate: ", "")} | {systems.Length} | {maxParticles} | {lights} |");
            }

            var sb = new StringBuilder();
            sb.AppendLine("# TD8: effect module inventory");
            sb.AppendLine();
            sb.AppendLine($"Generated by `demo3d unity EffectInventory` over the {candidates.Count} effect candidates in the manifest ");
            sb.AppendLine("and every child particle system. The converter implements exactly these entries.");
            sb.AppendLine();
            sb.AppendLine("## Candidates");
            sb.AppendLine();
            sb.AppendLine("| Prefab | Use | Systems | Max particles (sum) | Lights |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (var row in perPrefab) sb.AppendLine(row);
            sb.AppendLine();
            sb.AppendLine("## Entries in use");
            sb.AppendLine();
            sb.AppendLine("| Entry | Prefabs | Count |");
            sb.AppendLine("|---|---|---|");
            foreach (var kv in uses.Entries)
                sb.AppendLine($"| {kv.Key} | {string.Join(", ", kv.Value)} | {kv.Value.Count} |");
            Directory.CreateDirectory(Path.GetDirectoryName(outPath));
            File.WriteAllText(outPath, sb.ToString());
            Debug.Log($"EffectInventory: {candidates.Count} prefabs, {uses.Entries.Count} entries -> {outPath}");
        }

        static void Inspect(ParticleSystem ps, string prefab, Uses u)
        {
            var main = ps.main;
            u.Add("main", prefab);
            u.Add("main.simulationSpace: " + main.simulationSpace, prefab);
            u.Add("main.scalingMode: " + main.scalingMode, prefab);
            if (main.loop) u.Add("main.loop", prefab);
            if (main.prewarm) u.Add("main.prewarm", prefab);
            if (main.startSize3D) u.Add("main.startSize3D", prefab);
            if (main.startRotation3D) u.Add("main.startRotation3D", prefab);
            if (main.flipRotation != 0) u.Add("main.flipRotation", prefab);
            Curve(u, prefab, "main.startDelay", main.startDelay);
            Curve(u, prefab, "main.startLifetime", main.startLifetime);
            Curve(u, prefab, "main.startSpeed", main.startSpeed);
            Curve(u, prefab, "main.startSize", main.startSize);
            Curve(u, prefab, "main.startRotation", main.startRotation);
            Curve(u, prefab, "main.gravityModifier", main.gravityModifier);
            Gradient(u, prefab, "main.startColor", main.startColor);

            var em = ps.emission;
            if (em.enabled)
            {
                u.Add("emission", prefab);
                if (em.burstCount > 0) u.Add("emission.bursts", prefab);
                Curve(u, prefab, "emission.rateOverTime", em.rateOverTime, skipZero: true);
                Curve(u, prefab, "emission.rateOverDistance", em.rateOverDistance, skipZero: true);
            }
            var shape = ps.shape;
            if (shape.enabled)
            {
                u.Add("shape: " + shape.shapeType, prefab);
                if (shape.randomDirectionAmount > 0) u.Add("shape.randomDirection", prefab);
                if (shape.sphericalDirectionAmount > 0) u.Add("shape.sphericalDirection", prefab);
                if (shape.arc < 360f) u.Add("shape.arc<360 (" + shape.arcMode + ")", prefab);
                if (shape.shapeType == ParticleSystemShapeType.Mesh || shape.shapeType == ParticleSystemShapeType.MeshRenderer || shape.shapeType == ParticleSystemShapeType.SkinnedMeshRenderer)
                    u.Add("shape: mesh source", prefab);
            }
            Module(u, prefab, "velocityOverLifetime", ps.velocityOverLifetime.enabled);
            Module(u, prefab, "limitVelocityOverLifetime", ps.limitVelocityOverLifetime.enabled);
            Module(u, prefab, "inheritVelocity", ps.inheritVelocity.enabled);
            Module(u, prefab, "lifetimeByEmitterSpeed", ps.lifetimeByEmitterSpeed.enabled);
            Module(u, prefab, "forceOverLifetime", ps.forceOverLifetime.enabled);
            if (ps.colorOverLifetime.enabled) Gradient(u, prefab, "colorOverLifetime", ps.colorOverLifetime.color);
            Module(u, prefab, "colorBySpeed", ps.colorBySpeed.enabled);
            if (ps.sizeOverLifetime.enabled)
            {
                Curve(u, prefab, "sizeOverLifetime", ps.sizeOverLifetime.size);
                if (ps.sizeOverLifetime.separateAxes) u.Add("sizeOverLifetime.separateAxes", prefab);
            }
            Module(u, prefab, "sizeBySpeed", ps.sizeBySpeed.enabled);
            if (ps.rotationOverLifetime.enabled) Curve(u, prefab, "rotationOverLifetime", ps.rotationOverLifetime.z);
            Module(u, prefab, "rotationBySpeed", ps.rotationBySpeed.enabled);
            Module(u, prefab, "externalForces", ps.externalForces.enabled);
            if (ps.noise.enabled) u.Add("noise (quality " + ps.noise.quality + ")", prefab);
            if (ps.collision.enabled) u.Add("collision (" + ps.collision.type + ")", prefab);
            Module(u, prefab, "trigger", ps.trigger.enabled);
            if (ps.subEmitters.enabled && ps.subEmitters.subEmittersCount > 0)
                for (int i = 0; i < ps.subEmitters.subEmittersCount; i++)
                    u.Add("subEmitters: " + ps.subEmitters.GetSubEmitterType(i), prefab);
            if (ps.textureSheetAnimation.enabled)
                u.Add("textureSheetAnimation (" + ps.textureSheetAnimation.mode + ", " + ps.textureSheetAnimation.animation + ")", prefab);
            if (ps.lights.enabled) u.Add("lights", prefab);
            if (ps.trails.enabled) u.Add("trails (" + ps.trails.mode + ")", prefab);
            if (ps.customData.enabled) u.Add("customData", prefab);

            var r = ps.GetComponent<ParticleSystemRenderer>();
            if (r != null && r.enabled)
            {
                u.Add("renderer: " + r.renderMode, prefab);
                if (r.renderMode == ParticleSystemRenderMode.Mesh) u.Add("renderer: mesh " + (r.mesh != null ? r.mesh.name : "none"), prefab);
                if (r.alignment != ParticleSystemRenderSpace.View) u.Add("renderer.alignment: " + r.alignment, prefab);
                if (r.sortingFudge != 0) u.Add("renderer.sortingFudge", prefab);
                var streams = new List<ParticleSystemVertexStream>();
                r.GetActiveVertexStreams(streams);
                u.Add("vertexStreams: " + string.Join("+", streams), prefab);
                foreach (var m in r.sharedMaterials)
                    if (m != null) u.Add("shader: " + (m.shader != null ? m.shader.name : "missing"), prefab);
                if (r.trailMaterial != null && ps.trails.enabled) u.Add("trail shader: " + r.trailMaterial.shader.name, prefab);
            }
        }

        static void Module(Uses u, string prefab, string name, bool enabled)
        {
            if (enabled) u.Add(name, prefab);
        }

        static void Curve(Uses u, string prefab, string name, ParticleSystem.MinMaxCurve c, bool skipZero = false)
        {
            if (skipZero && c.mode == ParticleSystemCurveMode.Constant && c.constant == 0) return;
            u.Add(name + ": " + c.mode, prefab);
        }

        static void Gradient(Uses u, string prefab, string name, ParticleSystem.MinMaxGradient g) =>
            u.Add(name + ": " + g.mode, prefab);
    }
}
