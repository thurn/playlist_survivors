"""The sweep report (benchmarks.md, The report), generated from a sweep folder's rows.

Reads rows.jsonl (one per run), frontier.jsonl (one per point) and machine-*.json, and writes
report.md: the frontier tables with each point's limit and compute estimate, fill counts and the
envelope, the overdraw flags, the quiet-machine and thermal summary, and every run.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

GPU_LINE, CPU_LINE = 4.2, 10.4
TRANSPARENT_MEAN_FLAG, TRANSPARENT_PEAK_FLAG = 5.0, 12.0


def read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def fmt(v, digits: int = 2, unit: str = "") -> str:
    if v is None:
        return "–"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.{digits}f}{unit}"
    return f"{v:,}{unit}" if isinstance(v, int) else f"{v}{unit}"


def envelope(points: list[dict]) -> tuple[float, int | None] | None:
    """The widest measured width whose frontier fills its screen at 1 per m²; else 30 m."""
    if not points:
        return None
    qualifying = [p for p in points if p["n"] is not None and p["n"] >= round(p["visibleGroundM2"])]
    if qualifying:
        best = max(qualifying, key=lambda p: p["viewWidthM"])
    else:
        at30 = [p for p in points if p["viewWidthM"] == 30]
        if not at30:
            return None
        best = at30[0]
    n = best["n"]
    return best["viewWidthM"], None if n is None else n // 100 * 100


def build(folder: Path) -> str:
    rows = read_jsonl(folder / "rows.jsonl")
    frontier = read_jsonl(folder / "frontier.jsonl")
    machines = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(folder.glob("machine-*.json"))]
    out: list[str] = []
    w = out.append
    sweeps = sorted({r["sweep"] for r in rows})
    scenes = sorted({r["scene"] for r in rows})
    w(f"# Sweep report: {', '.join(scenes)}")
    w("")
    w(f"Generated by `demo3d report` from `{folder.name}`: sweeps {', '.join(sweeps)}; {len(rows)} runs, "
      f"{len(frontier)} frontier points. Pass lines: GPU p99 {GPU_LINE} ms, main and render thread p99 "
      f"{CPU_LINE} ms, no frame over twice its line (performance.md).")
    w("")
    if machines:
        m = machines[-1]
        w("## Machine")
        w("")
        w(f"{m.get('gpu')} (driver {m.get('driver')}, {m.get('api')}), {m.get('cpu')} "
          f"({m.get('logicalCores')} logical cores), memory {m.get('memMHz')} MHz, power plan "
          f"{m.get('powerPlanName')}, {m.get('jobWorkers')} job workers, backbuffer {m.get('backbuffer')}, "
          f"Unity {m.get('unity')} ({m.get('backend')}). At the start: GPU {m.get('gpuTempC')} °C, throttle "
          f"{m.get('gpuThrottle')}, other processes {m.get('otherCpuPctAtStart')}% CPU after a "
          f"{m.get('quietWaitS')} s wait.")
        w("")

    if frontier:
        w("## Frontier")
        w("")
        groups: dict[tuple, list[dict]] = defaultdict(list)
        for p in frontier:
            groups[(p["scene"], p["load"], p["aa"])].append(p)
        for (scene, load, aa), pts in groups.items():
            pts.sort(key=lambda p: p["viewWidthM"])
            w(f"### {scene}, load {load}, {aa}")
            w("")
            w("| view | frontier N | limit | GPU p99 | main p99 | render p99 | compute est. | fill count | "
              "fills | capacity | runs (probe+full) | fit confirmed | noisy runs | rests on noisy |")
            w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
            for p in pts:
                fill = round(p["visibleGroundM2"])
                n = p["n"]
                label = "below range" if n is None else f"{n:,}" + (" (capacity-bound)" if p["capacityBound"] else "")
                w(f"| {fmt(p['viewWidthM'])} m | {label} | {p['limit']} | {fmt(p['gpuP99Ms'])} ms | "
                  f"{fmt(p['mainP99Ms'])} ms | {fmt(p['renderP99Ms'])} ms | {fmt(p['computeEstimateMs'])} ms | "
                  f"{fill:,} | {fmt(n is not None and n >= fill)} | {p['capacity']:,} | "
                  f"{p['probeRuns']}+{p['fullRuns']} | {fmt(p['fitConfirmed'])} | {p['noisyRuns']} | "
                  f"{fmt(p['restsOnNoisy'])} |")
            w("")
            env = envelope(pts)
            if env:
                w(f"Envelope rule at this load and mode (the widest view whose frontier fills its screen at one "
                  f"monster per m²): **{fmt(env[0])} m, {fmt(env[1])} on screen**.")
                w("")
        resting = sum(1 for p in frontier if p["restsOnNoisy"])
        w(f"Frontier points resting on noisy runs: **{resting} of {len(frontier)}**.")
        w("")
        sims = [(p["viewWidthM"], p["simTickP99Ms"]) for p in frontier if p.get("simTickP99Ms") is not None]
        w("Sim tick p99 at the frontier points: " + (", ".join(f"{v} m {t:.2f} ms" for v, t in sims)
                                                   if sims else "none (the scene has no sim)") + ".")
        w("")

    flagged = [r for r in rows if (r.get("transparentPerPixel") or 0) > TRANSPARENT_MEAN_FLAG
               or (r.get("transparentBeatPeak") or 0) > TRANSPARENT_PEAK_FLAG]
    w("## Overdraw")
    w("")
    w(f"Runs whose mean transparent fragments per pixel exceed {TRANSPARENT_MEAN_FLAG:g} or whose beat-frame "
      f"peak exceeds {TRANSPARENT_PEAK_FLAG:g}: {len(flagged)} of {len(rows)}"
      + (" (" + ", ".join(f"n {r['n']} at {r['viewWidthM']} m: {fmt(r['transparentPerPixel'])}/"
                          f"{fmt(r['transparentBeatPeak'])}" for r in flagged[:8]) + ")" if flagged else "") + ".")
    w("")

    noisy = [r for r in rows if r["noisy"]]
    reasons: dict[str, int] = defaultdict(int)
    for r in noisy:
        for reason in r["noiseReasons"]:
            key = reason.split(" by ")[0].split(" to ")[0]
            if " used " in reason:
                key = "other processes' GPU" if "GPU" in reason else "other processes' CPU"
            reasons[key] += 1
    temps = [r["gpuTempC"] for r in rows if r.get("gpuTempC") is not None]
    throttles = sorted({t for r in rows for t in (r.get("gpuThrottle") or "none").split("|")})
    workers = sorted({r["jobWorkers"] for r in rows})
    w("## Quiet machine")
    w("")
    w(f"- Noisy runs: {len(noisy)} of {len(rows)}"
      + (" (" + "; ".join(f"{k}: {v}" for k, v in reasons.items()) + ")" if noisy else "") + ".")
    zero = [r.get("gpuZeroFrames", 0) / r["timedFrames"] for r in rows if r.get("timedFrames")]
    w(f"- Frames without a GPU time: at most {max(zero, default=0):.2%} of a run's timed frames "
      "(over 0.5% marks a run noisy).")
    w(f"- GPU temperature during runs: {min(temps, default=0):.0f} to {max(temps, default=0):.0f} °C; throttle "
      f"reasons seen: {', '.join(throttles)} (a power cap under full load is normal and not noise).")
    w(f"- Job workers in every row: {', '.join(str(x) for x in workers)}.")
    unfocused = sum(1 for r in rows if r.get("focusLost"))
    if unfocused:
        relaxed = any(m.get("requireForeground") is False for m in machines)
        w(f"- Runs during which the player's window didn't hold the foreground: {unfocused}"
          + (" (quiet.requireForeground was off: recorded, not counted as noise)" if relaxed else "") + ".")
    w("")

    w("## Runs")
    w("")
    w("| sweep | point | kind | n | attempt | GPU p99 | GPU max | main p99 | render p99 | on screen | opaque depth "
      "| transp./px | beat peak | GPU °C | throttle | other CPU | other GPU | pass | noisy |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        w(f"| {r['sweep']} | {fmt(r['viewWidthM'])} m/{r['load']}/{r['aa']} | {r['kind']} | {r['n']:,} | "
          f"{r['attempt']} | {fmt(r['gpuP99Ms'])} | {fmt(r['gpuMaxMs'])} | {fmt(r['mainP99Ms'])} | "
          f"{fmt(r['renderP99Ms'])} | {fmt(r['onScreenAlive'])} | {fmt(r['opaqueDepth'])} | "
          f"{fmt(r['transparentPerPixel'])} | {fmt(r['transparentBeatPeak'])} | {fmt(r['gpuTempC'], 0)} | "
          f"{r['gpuThrottle']} | {fmt(r['otherCpuPctMax'], 1)}% | {fmt(r.get('otherGpuPctMax'), 1)}% | "
          f"{fmt(r['pass'])} | {fmt(r['noisy'])} |")
    w("")
    return "\n".join(out)


def write(folder: Path) -> Path:
    path = folder / "report.md"
    path.write_text(build(folder), encoding="utf-8")
    return path


def cmd_report(a) -> int:
    print(f"report: {write(Path(a.folder))}")
    return 0
