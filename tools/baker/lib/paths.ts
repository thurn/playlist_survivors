import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
export const ASSETS_SRC = join(REPO, "assets-src");
export const OUT = join(REPO, "public/assets");
export const SFX_OUT = join(OUT, "sfx");
export const CAPTURES = join(REPO, "captures");

/** Local LPC collections (read-only inputs). Override with LPC_ROOT. */
export const LPC_ROOT = process.env.LPC_ROOT ?? join(homedir(), "Documents/lpc");
export const ULPC = join(LPC_ROOT, "ulpc-generator");

/** Download cache, outside the repository. Override with PS_CACHE. */
export const CACHE = process.env.PS_CACHE ?? join(homedir(), ".cache/playlist-survivors");
export const DOWNLOADS = join(CACHE, "downloads");
export const EXTRACTED = join(CACHE, "extracted");

/**
 * Source references used throughout the baker inputs:
 * - `ulpc:<path under spritesheets/>`   generator art, licensed via CREDITS.csv
 * - `lpc:<path under LPC_ROOT>`          local packs, licensed via licences.yaml
 * - `dl:<source id>/<path in archive>`   downloaded packs, licensed via licences.yaml
 * - `gen:<name>`                         art generated by the baker itself
 */
export function resolveSource(ref: string): string {
  // A "#region" suffix names a reviewed part of a file; it does not change the path.
  ref = ref.split("#")[0];
  const [scheme, ...rest] = ref.split(":");
  const p = rest.join(":");
  switch (scheme) {
    case "ulpc":
      return join(ULPC, "spritesheets", p);
    case "lpc":
      return join(LPC_ROOT, p);
    case "dl": {
      const [id, ...inner] = p.split("/");
      return join(EXTRACTED, id, inner.join("/"));
    }
    default:
      throw new Error(`cannot resolve source reference ${ref}`);
  }
}
